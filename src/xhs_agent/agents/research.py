def _detect_category(topic: str) -> str:
    for category, keywords in _CATEGORY_KEYWORDS:
        if any(kw in topic for kw in keywords):
            return category
    return "默认"


class MockResearchAgent:
    """Mock 研究 Agent：根据用户输入生成结构化选题简报。

    确定性输出，便于测试；未来可用真实 LLM 实现替换（实现
    :class:`~xhs_agent.agents.base.ResearchAgent` 协议）。
    """

    def research(self, topic: str) -> ResearchBrief:
        category = _detect_category(topic)
        info = _CATEGORY_INFO.get(category, _DEFAULT_INFO)
        keywords = list(dict.fromkeys([topic, *info["keywords"]]))
        tags = info["tags"] or ["#" + topic]
        return ResearchBrief(
            topic=topic,
            target_audience=info["audience"],
            pain_points=info["pain_points"],
            angles=info["angles"],
            keywords=keywords,
            tags=tags,
        )
